#!/usr/bin/env python3
"""Generates plugins/index.json.

Reads plugins/<slug>/manifest.json, checks what the schema alone can't (the
entry exists, kind names are unique, folders are slugs), hashes each folder,
and writes one row per plugin: what the store shows, and what to fetch to
install it. Nothing in a plugin is run.

    tools/generate.py                 # write the index
    tools/generate.py --check         # fail if the index is stale or a plugin invalid
    tools/generate.py --validate      # fail if a plugin is invalid; write nothing
    tools/generate.py --root <dir>    # operate on another tree (tests)

The index is generated by CI on content branches; never edit it by hand.
Standard library only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

SLUG = re.compile(r"^[a-z0-9][a-z0-9-]*$")
IGNORED = {"__pycache__", ".DS_Store"}

# What the store shows before anything is fetched.
LISTING_FIELDS = (
    "name", "version", "summary", "description", "vendor", "symbol", "tint",
    "category", "homepage", "contributors",
)


def folder_files(folder: Path) -> list[dict]:
    """Each file in a folder, sorted by path, with its sha256 and size —
    what a client fetches one by one over plain HTTP."""
    files = sorted(
        path for path in folder.rglob("*")
        if path.is_file() and not IGNORED & set(path.relative_to(folder).parts)
    )
    return [
        {
            "path": path.relative_to(folder).as_posix(),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "size": path.stat().st_size,
        }
        for path in files
    ]


def folder_hash(files: list[dict]) -> str:
    """sha256 over "<path>\\0<file sha256>\\n" for each file, in path order.
    Clients recompute it over what they fetched."""
    digest = hashlib.sha256()
    for file in files:
        digest.update(f"{file['path']}\0{file['sha256']}\n".encode())
    return digest.hexdigest()


def plugin_rows(root: Path) -> tuple[list[dict], list[str]]:
    rows, problems = [], []
    base = root / "plugins"
    for folder in sorted(p for p in base.iterdir() if p.is_dir() and p.name not in IGNORED):
        slug = folder.name
        if not SLUG.match(slug):
            problems.append(f"plugins/{slug}: folder name is not a lowercase slug")
            continue
        try:
            manifest = json.loads((folder / "manifest.json").read_text())
        except (OSError, ValueError) as error:
            problems.append(f"plugins/{slug}: unreadable manifest.json ({error})")
            continue
        entry = manifest.get("entry", "plugin.py")
        if not (folder / entry).is_file():
            problems.append(f"plugins/{slug}: entry {entry!r} is missing")
        kinds = [kind.get("name") for kind in manifest.get("kinds", [])]
        if len(kinds) != len(set(kinds)):
            problems.append(f"plugins/{slug}: kind names repeat")
        files = folder_files(folder)
        row = {"slug": slug}
        row.update({k: manifest[k] for k in LISTING_FIELDS if k in manifest})
        row.update({
            "entry": entry,
            "kinds": kinds,
            "path": f"plugins/{slug}",
            "sha256": folder_hash(files),
            "files": files,
        })
        rows.append(row)
    return rows, problems


def generate(root: Path) -> tuple[dict[Path, str], list[str]]:
    """The index to write, keyed by path, and any problems found. The
    scaffold itself has no plugins, so it has no index."""
    if not (root / "plugins").is_dir():
        return {}, []
    rows, problems = plugin_rows(root)
    text = json.dumps({"plugins": rows}, indent=2, ensure_ascii=False) + "\n"
    return {root / "plugins" / "index.json": text}, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the index is stale or a plugin is invalid")
    parser.add_argument("--validate", action="store_true",
                        help="fail if a plugin is invalid; write nothing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args()
    root = args.root.resolve()

    outputs, problems = generate(root)
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if problems:
        return 1
    if args.validate:
        return 0

    if args.check:
        stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text() != text]
        for path in stale:
            print(f"error: {path.relative_to(root)} is stale; run tools/generate.py", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
