#!/usr/bin/env python3
"""Generates discovery/index.json and plugins/index.json.

Reads plugins/<slug>/manifest.json and discovery/<slug>/action.json, checks
what the schemas alone can't (entries exist, secrets are declared before
they're referenced, slugs are unique, curation names real actions), hashes
each folder, and writes both indexes. Nothing in a plugin or action is run.

    tools/generate.py                 # write both indexes
    tools/generate.py --check         # fail if an index is stale or an entry invalid
    tools/generate.py --validate      # fail if an entry is invalid; write nothing
    tools/generate.py --root <dir>    # operate on another tree (tests)

Indexes are generated by CI on content branches; never edit them by hand.
Standard library only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

SLUG = re.compile(r"^[a-z0-9][a-z0-9-]*$")
SECRET_REF = re.compile(r"\$\{secret:([a-z][a-z0-9_]*)\}")
IGNORED = {"__pycache__", ".DS_Store"}

# What the store shows before anything is fetched.
LISTING_FIELDS = (
    "name", "version", "summary", "vendor", "symbol", "tint", "category",
    "homepage", "contributors",
)


class Invalid(Exception):
    pass


def folder_hash(folder: Path) -> str:
    """sha256 over the sorted (path, file sha256) pairs of a folder."""
    digest = hashlib.sha256()
    files = sorted(
        path for path in folder.rglob("*")
        if path.is_file() and not IGNORED & set(path.relative_to(folder).parts)
    )
    for path in files:
        digest.update(path.relative_to(folder).as_posix().encode())
        digest.update(b"\0")
        digest.update(hashlib.sha256(path.read_bytes()).hexdigest().encode())
        digest.update(b"\n")
    return digest.hexdigest()


def secret_references(value: object) -> set[str]:
    if isinstance(value, str):
        return set(SECRET_REF.findall(value))
    if isinstance(value, dict):
        return set().union(set(), *(secret_references(v) for v in value.values()))
    if isinstance(value, list):
        return set().union(set(), *(secret_references(v) for v in value))
    return set()


def entries(root: Path, section: str, filename: str):
    """(slug, folder, parsed json) for each entry folder, reporting problems."""
    base = root / section
    if not base.is_dir():
        return
    for folder in sorted(p for p in base.iterdir() if p.is_dir() and p.name not in IGNORED):
        name = f"{section}/{folder.name}"
        if not SLUG.match(folder.name):
            raise Invalid(f"{name}: folder name is not a lowercase slug")
        try:
            data = json.loads((folder / filename).read_text())
        except (OSError, ValueError) as error:
            raise Invalid(f"{name}: unreadable {filename} ({error})")
        yield folder.name, folder, data


def plugin_rows(root: Path) -> tuple[list[dict], list[dict], list[str]]:
    listings, installs, problems = [], [], []
    for slug, folder, manifest in entries(root, "plugins", "manifest.json"):
        entry = manifest.get("entry", "plugin.py")
        if not (folder / entry).is_file():
            problems.append(f"plugins/{slug}: entry {entry!r} is missing")
        kinds = [kind.get("name") for kind in manifest.get("kinds", [])]
        if len(kinds) != len(set(kinds)):
            problems.append(f"plugins/{slug}: kind names repeat")
        sha = folder_hash(folder)
        path = f"plugins/{slug}"
        listing = {"slug": slug, "type": "plugin"}
        listing.update({k: manifest[k] for k in LISTING_FIELDS if k in manifest})
        listing.update({"path": path, "sha256": sha})
        listings.append(listing)
        installs.append({
            "slug": slug,
            "name": manifest.get("name"),
            "version": manifest.get("version"),
            "entry": entry,
            "kinds": kinds,
            "path": path,
            "sha256": sha,
        })
    return listings, installs, problems


def action_rows(root: Path) -> tuple[list[dict], list[str]]:
    rows, problems = [], []
    for slug, folder, action in entries(root, "discovery", "action.json"):
        kind = action.get("type")
        if kind not in action:
            problems.append(f"discovery/{slug}: missing its {kind!r} section")
        declared = {secret.get("key") for secret in action.get("secrets", [])}
        for key in sorted(secret_references(action.get(kind)) - declared):
            problems.append(f"discovery/{slug}: references ${{secret:{key}}} but doesn't declare it")
        if kind == "skill":
            skill_root = action.get("skill", {}).get("root", "")
            if not (folder / skill_root / "SKILL.md").is_file():
                problems.append(f"discovery/{slug}: skill root {skill_root!r} has no SKILL.md")
        row = {"slug": slug, "type": kind}
        row.update({k: action[k] for k in LISTING_FIELDS if k in action})
        if action.get("secrets"):
            row["secrets"] = [secret.get("label") for secret in action["secrets"]]
        row.update({"path": f"discovery/{slug}", "sha256": folder_hash(folder)})
        rows.append(row)
    return rows, problems


def curation(root: Path, slugs: set[str]) -> tuple[dict | None, list[str]]:
    path = root / "curation.json"
    if not path.is_file():
        return None, []
    try:
        data = json.loads(path.read_text())
    except ValueError as error:
        return None, [f"curation.json: unreadable ({error})"]
    named = list(data.get("featured", []))
    for collection in data.get("collections", []):
        named += collection.get("items", [])
    data.pop("$schema", None)
    return data, [f"curation.json: {slug!r} isn't a listed action" for slug in named if slug not in slugs]


def generate(root: Path) -> tuple[dict[Path, str], list[str]]:
    """The index files to write, keyed by path, and any problems found."""
    try:
        listings, installs, problems = plugin_rows(root)
        actions, action_problems = action_rows(root)
    except Invalid as error:
        return {}, [str(error)]
    problems += action_problems

    plugin_slugs = {row["slug"] for row in listings}
    for row in actions:
        if row["slug"] in plugin_slugs:
            problems.append(f"discovery/{row['slug']}: slug is already a plugin")

    everything = sorted(listings + actions, key=lambda row: row["slug"])
    curated, curation_problems = curation(root, {row["slug"] for row in everything})
    problems += curation_problems

    discovery = {"actions": everything}
    if curated:
        discovery["curation"] = curated

    def render(value: dict) -> str:
        return json.dumps(value, indent=2, ensure_ascii=False) + "\n"

    # The scaffold itself has no content, so it has no indexes.
    outputs = {}
    if (root / "plugins").is_dir() or (root / "discovery").is_dir():
        outputs[root / "discovery" / "index.json"] = render(discovery)
    if (root / "plugins").is_dir():
        outputs[root / "plugins" / "index.json"] = render({"plugins": installs})
    return outputs, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if an index is stale or an entry is invalid")
    parser.add_argument("--validate", action="store_true",
                        help="fail if an entry is invalid; write nothing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args()

    outputs, problems = generate(args.root.resolve())
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if problems:
        return 1
    if args.validate:
        return 0

    if args.check:
        stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text() != text]
        for path in stale:
            print(f"error: {path.relative_to(args.root.resolve())} is stale; run tools/generate.py",
                  file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(args.root.resolve())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
